#!/usr/bin/env node
/**
 * Build `src/tiles/art/taiwan.generated.ts` from the SVG files in
 * `assets/tiles/taiwan`.
 *
 * Each face becomes a self-contained SVG string keyed by its engine tile code.
 * Along the way it is cut down to the subset react-native-svg draws the same
 * everywhere: the title and description move out into a `label` (kept so a
 * test can check every tile got the right file), ids go, and the two winds
 * drawn through a self-mask (西, 北) are flattened to their plain path. That
 * mask only thinned the strokes by under a unit in a 300-unit box, and ids
 * repeated across two copies of one tile collide on a web page.
 *
 *   node scripts/build-tile-art.mjs
 */
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = join(root, 'assets/tiles/taiwan');
const OUT = join(root, 'src/tiles/art/taiwan.generated.ts');

/** File name (minus its `NN-` order prefix) → engine tile code. */
const NAMED = {
  'white-dragon': 'dw', 'green-dragon': 'dg', 'red-dragon': 'dr',
  'east-wind': 'we', 'south-wind': 'ws', 'west-wind': 'ww', 'north-wind': 'wn',
  plum: 'f1', orchid: 'f2', chrysanthemum: 'f3', bamboo: 'f4',
  spring: 'f5', summer: 'f6', autumn: 'f7', winter: 'f8',
};
const SUIT = { characters: 'w', circles: 't', bamboos: 'b' };

/**
 * The artist draws every face in a 300×420 box, but the drawing itself only
 * spans x 22.5–277.5, y 28.5–390.2 across all 42 (measured from the published
 * PNGs). Left as is, that margin plus the tile body's own made the faces look
 * like miniatures, so each face is re-boxed to the union with a few units' air.
 * Keep in step with `ART_VIEWBOX` in src/tiles/tileArt.ts.
 */
const CROP = '16 22 268 376';

function codeFor(file) {
  const name = file.replace(/^\d+-/, '').replace(/\.svg$/, '');
  const suited = /^(characters|circles|bamboos)-([1-9])$/.exec(name);
  if (suited) return `${suited[2]}${SUIT[suited[1]]}`;
  if (NAMED[name]) return NAMED[name];
  throw new Error(`${file}: no tile code for this file name`);
}

/** Replace a `<defs>` path drawn through its own mask with that path, filled. */
function flattenSelfMask(svg, file) {
  if (!svg.includes('<mask')) return svg;
  const path = /<defs>(<path [^>]*?)\/>.*?<\/defs>/s.exec(svg);
  const fill = /<use [^>]*fill="(#[0-9A-Fa-f]{6})"[^>]*mask=/.exec(svg);
  if (!path || !fill) throw new Error(`${file}: unrecognised mask structure`);
  return svg
    .replace(/<defs>.*?<\/defs>/s, '')
    .replace(/<use [^>]*mask="[^"]*"[^>]*\/>/, `${path[1]} fill="${fill[1]}"/>`);
}

function clean(svg, file) {
  const label = /<title[^>]*>([^<]*)<\/title>/.exec(svg)?.[1];
  if (!label) throw new Error(`${file}: no <title> to label it with`);
  const xml = flattenSelfMask(svg, file)
    .replace(/<title[^>]*>.*?<\/title>/s, '')
    .replace(/<desc[^>]*>.*?<\/desc>/s, '')
    .replace(/ (id|aria-labelledby|role)="[^"]*"/g, '')
    // The size is set where the face is drawn, so the root <svg> keeps only its viewBox.
    .replace(/^<svg[^>]*>/, (tag) => tag
      .replace(/ (width|height)="[^"]*"/g, '')
      .replace(/viewBox="0 0 300 420"/, `viewBox="${CROP}"`))
    .replace(/\s+/g, ' ')
    .trim();
  return { label, xml };
}

const entries = readdirSync(SRC)
  .filter((f) => f.endsWith('.svg'))
  .sort()
  .map((file) => [codeFor(file), clean(readFileSync(join(SRC, file), 'utf8'), file)]);

const body = entries
  .map(([code, { label, xml }]) => `  '${code}': {\n    label: ${JSON.stringify(label)},\n    xml: ${JSON.stringify(xml)},\n  },`)
  .join('\n');

writeFileSync(OUT, `// GENERATED by scripts/build-tile-art.mjs from assets/tiles/taiwan. Do not edit.
// Artwork by samoheen (github.com/samoheen/mahjong-tiles), public domain (CC0).
import type { TileKind } from '@mahjong/engine';
import type { TileArt } from '../tileArt';

export const TAIWAN_ART: Record<TileKind, TileArt> = {
${body}
};
`);
console.log(`wrote ${entries.length} faces to ${OUT}`);
